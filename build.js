#!/usr/bin/env node
// Builds index.html from web/page.html by inlining pw.js, words.txt and
// web/page.js into its script, then pinning the inline script and style by
// SHA-256 in the page's Content-Security-Policy.
//
//   node build.js           write index.html
//   node build.js FILE      write FILE instead (the deploy workflow uses this)

"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { isValidWordList } = require("./pw.js");

const read = (file) => fs.readFileSync(path.join(__dirname, file), "utf8");
const sha256 = (text) => crypto.createHash("sha256").update(text).digest("base64");

function build() {
  const words = read("words.txt").split(/\s+/).filter(Boolean);
  if (!isValidWordList(words)) throw new Error("words.txt must hold distinct lowercase words");

  // Wrap the words into lines of at most 96 characters.
  const lines = [];
  let line = "";
  for (const word of words) {
    if (line && line.length + 1 + word.length > 96) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  lines.push(line);

  const script = [
    "",
    read("pw.js").replace(/^#!.*\n/, "").trim(),
    "",
    "// The word list, from words.txt.",
    "const WORDS = `",
    ...lines,
    "`.trim().split(/\\s+/);",
    "",
    read("web/page.js").trim(),
    "",
  ].join("\n");
  if (/<\/script/i.test(script)) throw new Error("the script must not contain </script");

  let html = read("web/page.html");
  const placeholder = "<script>\n/* build.js puts pw.js, words.txt and web/page.js here */\n</script>";
  if (!html.includes(placeholder)) throw new Error("web/page.html is missing the script placeholder");
  html = html
    .replace(placeholder, () => `<script>${script}</script>`)
    .replace("<!-- GENERATED_NOTE -->",
      "<!-- Generated by build.js from web/page.html, pw.js, words.txt and web/page.js. Edit those, not this. -->");

  const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
  return html
    .replace("'sha256-SCRIPT_HASH'", `'sha256-${sha256(script)}'`)
    .replace("'sha256-STYLE_HASH'", `'sha256-${sha256(style)}'`);
}

if (require.main === module) {
  const out = process.argv[2] || path.join(__dirname, "index.html");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, build());
  console.log(`wrote ${out}`);
}

module.exports = { build };
